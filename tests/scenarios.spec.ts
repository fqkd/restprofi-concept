import { expect, test } from '@playwright/test'

test('заказ сохраняется после ошибки и завершается со второй попытки', async ({ page }) => {
  await page.goto('#/')
  await page.getByRole('button', { name: /Заказать еду/ }).click()
  await expect(page.getByRole('heading', { name: /Где хотите/ })).toBeVisible()
  await page.getByRole('button', { name: /Питькофе/ }).click()
  await page.getByRole('button', { name: /Смотреть доступное меню/ }).click()
  await page.getByRole('button', { name: /Открыть Ньокки/ }).click()
  await page.getByRole('button', { name: /Добавить ·/ }).click()
  await page.getByRole('button', { name: /К оформлению/ }).click()
  await page.getByRole('textbox', { name: 'Имя' }).fill('Тест')
  await page.getByRole('textbox', { name: 'Телефон' }).fill('+70000000000')
  await page.getByRole('button', { name: 'Выбрать' }).last().click()
  await page.getByRole('dialog', { name: 'Выбор оплаты' }).getByRole('button', { name: 'Банковская карта' }).click()
  await page.getByRole('button', { name: /Подтвердить заказ/ }).click()
  await expect(page.getByRole('heading', { name: 'Корзина на месте' })).toBeVisible()
  await page.getByRole('button', { name: 'Вернуться к оплате' }).click()
  await expect(page.getByText('Банковская карта')).toBeVisible()
  await page.getByRole('button', { name: /Подтвердить заказ/ }).click()
  await expect(page.getByRole('heading', { name: 'Заказ сохранён' })).toBeVisible()
})


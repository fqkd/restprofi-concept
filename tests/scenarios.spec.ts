test('презентация и ключевые deep links открываются напрямую', async ({ page }) => {
  await page.goto('case/')
  await expect(page.getByRole('heading', { name: /Сначала задача/ })).toBeVisible()
  const caseUrl = page.url()
  const hrefs = await page.locator('a[href*="#/"]').evaluateAll((links) => links.map((link) => link.getAttribute('href')))
  expect(hrefs.length).toBeGreaterThanOrEqual(6)
  for (const href of hrefs) {
    await page.goto(new URL(href!, caseUrl).href)
    await expect(page.locator('#root')).not.toBeEmpty()
  }
  await page.goto('case/')
  await expect(page.locator('a[href="mailto:hello@eh.works"]')).toHaveCount(1)
  await expect(page.locator('a[href="https://eh.works"]')).toHaveCount(1)
  await page.goto('#/repeat')
  await expect(page.getByRole('heading', { name: 'Нет заказа для повтора' })).toBeVisible()
})

